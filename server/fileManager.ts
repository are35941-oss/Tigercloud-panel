import fs from 'fs';
import path from 'path';
import AdmZip from 'adm-zip';
import sharp from 'sharp';
import { FileEntry, MinecraftServer } from './types.js';

export class FileManager {
  /**
   * Sanitizes and verifies that a relative path does not escape the server volume root.
   */
  public static resolveSafePath(server: MinecraftServer, relPath: string): string {
    const cleanRel = (relPath || '').replace(/^\/+/, '');
    const fullPath = path.resolve(server.volumePath, cleanRel);
    const rootPath = path.resolve(server.volumePath);

    if (!fullPath.startsWith(rootPath)) {
      throw new Error('Access denied: Path traversal attempt outside container volume root');
    }
    return fullPath;
  }

  public static ensureServerFiles(server: MinecraftServer) {
    const dir = server.volumePath;
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }

    // eula.txt
    const eulaPath = path.join(dir, 'eula.txt');
    if (!fs.existsSync(eulaPath)) {
      fs.writeFileSync(eulaPath, '# By changing the setting below to TRUE you are indicating your agreement to the Mojang EULA\neula=true\n', 'utf-8');
    }

    // server.properties
    const propsPath = path.join(dir, 'server.properties');
    if (!fs.existsSync(propsPath)) {
      const defaultProps = `# Minecraft server properties
# Auto-generated by ObsidianNode Panel
motd=${server.motd || 'ObsidianNode High-Performance Minecraft Server'}
server-port=${server.port}
max-players=${server.maxPlayers || 20}
difficulty=normal
gamemode=survival
hardcore=false
pvp=true
spawn-monsters=true
spawn-animals=true
spawn-npcs=true
generate-structures=true
allow-flight=false
white-list=false
online-mode=true
enable-rcon=${!!server.rconPort}
rcon.port=${server.rconPort || 25575}
rcon.password=ObsidianRconSecret123
view-distance=10
simulation-distance=8
enable-command-block=true
level-name=world
level-type=minecraft\\:normal
sync-chunk-writes=true
`;
      fs.writeFileSync(propsPath, defaultProps, 'utf-8');
    }

    // whitelist.json
    const whitelistPath = path.join(dir, 'whitelist.json');
    if (!fs.existsSync(whitelistPath)) {
      fs.writeFileSync(whitelistPath, '[\n  {\n    "uuid": "4566e69f-c907-48ee-8d71-d7ba5aa00d20",\n    "name": "Steve"\n  }\n]\n', 'utf-8');
    }

    // ops.json
    const opsPath = path.join(dir, 'ops.json');
    if (!fs.existsSync(opsPath)) {
      fs.writeFileSync(opsPath, '[\n  {\n    "uuid": "4566e69f-c907-48ee-8d71-d7ba5aa00d20",\n    "name": "Steve",\n    "level": 4,\n    "bypassesPlayerLimit": false\n  }\n]\n', 'utf-8');
    }

    // bukkit.yml / paper-global.yml
    const paperYml = path.join(dir, 'paper-global.yml');
    if (!fs.existsSync(paperYml)) {
      fs.writeFileSync(paperYml, `# Paper Global Configuration
chunk-loading-advanced-player-teleport: false
async-chunks:
  threads: -1
player-auto-save-rate: -1
max-auto-save-chunks-per-tick: 24
`, 'utf-8');
    }

    // plugins and world directories
    const pluginsDir = path.join(dir, 'plugins');
    if (!fs.existsSync(pluginsDir)) {
      fs.mkdirSync(pluginsDir, { recursive: true });
    }
    const worldDir = path.join(dir, 'world');
    if (!fs.existsSync(worldDir)) {
      fs.mkdirSync(worldDir, { recursive: true });
    }
  }

  public static list(server: MinecraftServer, relPath = ''): FileEntry[] {
    this.ensureServerFiles(server);
    const targetPath = this.resolveSafePath(server, relPath);

    if (!fs.existsSync(targetPath)) {
      return [];
    }

    const items = fs.readdirSync(targetPath, { withFileTypes: true });
    return items.map(item => {
      const full = path.join(targetPath, item.name);
      let size = 0;
      let updatedAt = new Date().toISOString();
      try {
        const stats = fs.statSync(full);
        size = stats.size;
        updatedAt = stats.mtime.toISOString();
      } catch (err) {
        // ignore locked files
      }

      const relativeItemPath = path.relative(server.volumePath, full).replace(/\\/g, '/');

      return {
        name: item.name,
        path: relativeItemPath,
        isDirectory: item.isDirectory(),
        size,
        updatedAt,
        extension: item.isDirectory() ? undefined : path.extname(item.name).replace('.', '').toLowerCase(),
      };
    }).sort((a, b) => {
      // Directories first, then alphabetical
      if (a.isDirectory && !b.isDirectory) return -1;
      if (!a.isDirectory && b.isDirectory) return 1;
      return a.name.localeCompare(b.name);
    });
  }

  public static read(server: MinecraftServer, relPath: string): string {
    const targetPath = this.resolveSafePath(server, relPath);
    if (!fs.existsSync(targetPath)) {
      throw new Error(`File not found: ${relPath}`);
    }
    const stat = fs.statSync(targetPath);
    if (stat.isDirectory()) {
      throw new Error(`Cannot read directory as file: ${relPath}`);
    }
    return fs.readFileSync(targetPath, 'utf-8');
  }

  public static write(server: MinecraftServer, relPath: string, content: string): void {
    const targetPath = this.resolveSafePath(server, relPath);
    const dir = path.dirname(targetPath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    fs.writeFileSync(targetPath, content, 'utf-8');
  }

  public static createDirectory(server: MinecraftServer, relPath: string): void {
    const targetPath = this.resolveSafePath(server, relPath);
    if (fs.existsSync(targetPath)) {
      throw new Error(`Directory or file already exists: ${relPath}`);
    }
    fs.mkdirSync(targetPath, { recursive: true });
  }

  public static rename(server: MinecraftServer, oldRelPath: string, newRelPath: string): void {
    const sourcePath = this.resolveSafePath(server, oldRelPath);
    const destinationPath = this.resolveSafePath(server, newRelPath);

    if (!fs.existsSync(sourcePath)) {
      throw new Error(`Source path not found: ${oldRelPath}`);
    }
    if (fs.existsSync(destinationPath)) {
      throw new Error(`Target destination already exists: ${newRelPath}`);
    }

    const parentDir = path.dirname(destinationPath);
    if (!fs.existsSync(parentDir)) {
      fs.mkdirSync(parentDir, { recursive: true });
    }

    fs.renameSync(sourcePath, destinationPath);
  }

  public static delete(server: MinecraftServer, relPath: string): void {
    const targetPath = this.resolveSafePath(server, relPath);
    if (fs.existsSync(targetPath)) {
      const stats = fs.statSync(targetPath);
      if (stats.isDirectory()) {
        fs.rmSync(targetPath, { recursive: true, force: true });
      } else {
        fs.unlinkSync(targetPath);
      }
    }
  }

  public static zip(server: MinecraftServer, sourceRelPath: string, targetZipName?: string): string {
    const sourcePath = this.resolveSafePath(server, sourceRelPath);
    if (!fs.existsSync(sourcePath)) {
      throw new Error(`Source not found: ${sourceRelPath}`);
    }

    const stats = fs.statSync(sourcePath);
    const defaultZipName = `${path.basename(sourcePath)}.zip`;
    const zipName = targetZipName || defaultZipName;
    const parentDir = stats.isDirectory() ? path.dirname(sourcePath) : path.dirname(sourcePath);
    const targetZipPath = path.join(parentDir, zipName);

    // Ensure target doesn't escape volume
    if (!targetZipPath.startsWith(path.resolve(server.volumePath))) {
      throw new Error('Target zip path outside volume');
    }

    const zip = new AdmZip();
    if (stats.isDirectory()) {
      zip.addLocalFolder(sourcePath);
    } else {
      zip.addLocalFile(sourcePath);
    }

    zip.writeZip(targetZipPath);
    return path.relative(server.volumePath, targetZipPath).replace(/\\/g, '/');
  }

  public static unzip(server: MinecraftServer, zipRelPath: string, destRelDir = ''): void {
    const zipPath = this.resolveSafePath(server, zipRelPath);
    if (!fs.existsSync(zipPath)) {
      throw new Error(`Zip archive not found: ${zipRelPath}`);
    }

    const destPath = this.resolveSafePath(server, destRelDir);
    if (!fs.existsSync(destPath)) {
      fs.mkdirSync(destPath, { recursive: true });
    }

    const zip = new AdmZip(zipPath);
    const entries = zip.getEntries();
    const rootResolved = path.resolve(destPath);

    // Protect against Zip Slip vulnerabilities
    for (const entry of entries) {
      const entryDest = path.resolve(destPath, entry.entryName);
      if (!entryDest.startsWith(rootResolved)) {
        throw new Error(`Malicious zip entry detected (Zip Slip): ${entry.entryName}`);
      }
    }

    zip.extractAllTo(destPath, true);
  }

  public static async saveIcon(server: MinecraftServer, buffer: Buffer): Promise<{ iconDataUrl: string }> {
    this.ensureServerFiles(server);
    const iconPath = path.join(server.volumePath, 'server-icon.png');

    // Resize, crop to center, and enforce strictly 64x64 PNG format per Minecraft protocol specification
    const processedPng = await sharp(buffer)
      .resize(64, 64, {
        fit: 'cover',
        position: 'center',
      })
      .png({ compressionLevel: 9 })
      .toBuffer();

    fs.writeFileSync(iconPath, processedPng);
    const iconDataUrl = `data:image/png;base64,${processedPng.toString('base64')}`;
    return { iconDataUrl };
  }

  public static getIconBase64(server: MinecraftServer): string | null {
    const iconPath = path.join(server.volumePath, 'server-icon.png');
    if (!fs.existsSync(iconPath)) {
      return null;
    }
    try {
      const buf = fs.readFileSync(iconPath);
      return `data:image/png;base64,${buf.toString('base64')}`;
    } catch {
      return null;
    }
  }

  public static deleteIcon(server: MinecraftServer): boolean {
    const iconPath = path.join(server.volumePath, 'server-icon.png');
    if (fs.existsSync(iconPath)) {
      fs.unlinkSync(iconPath);
      return true;
    }
    return false;
  }

  public static updateMotdInProperties(server: MinecraftServer, rawMotd: string): void {
    this.ensureServerFiles(server);
    const propsPath = path.join(server.volumePath, 'server.properties');
    let content = '';
    if (fs.existsSync(propsPath)) {
      content = fs.readFileSync(propsPath, 'utf-8');
    }

    // Escape backslashes for properties file format
    const safeMotd = rawMotd.replace(/\\/g, '\\\\').replace(/\n/g, '\\n');
    const motdRegex = /^motd=.*$/m;

    if (motdRegex.test(content)) {
      content = content.replace(motdRegex, `motd=${safeMotd}`);
    } else {
      content += `\nmotd=${safeMotd}\n`;
    }

    fs.writeFileSync(propsPath, content, 'utf-8');
  }
}
